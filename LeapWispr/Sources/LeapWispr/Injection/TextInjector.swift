import Foundation
import AppKit
import CoreGraphics
import ApplicationServices

@MainActor
public final class TextInjector {
    public static let shared = TextInjector()
    
    private init() {}
    
    public func isAccessibilityTrusted() -> Bool {
        return AXIsProcessTrusted()
    }
    
    public static func isAccessibilityTrusted() -> Bool {
        return AXIsProcessTrusted()
    }
    
    public static func requestAccessibilityPermission() {
        let options = [kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String: true]
        AXIsProcessTrustedWithOptions(options as CFDictionary)
    }
    
    /// Bulletproof, single-execution text injection across 100% of macOS applications:
    /// 1. Puts polished text on standard system pasteboard with transient markers.
    /// 2. Reactivates target application and yields activation.
    /// 3. Executes the full, authentic hardware Cmd+V sequence:
    ///    - Cmd KeyDown (0x37)
    ///    - V KeyDown (0x09) with 25ms dwell time
    ///    - V KeyUp (0x09)
    ///    - Cmd KeyUp (0x37)
    ///    Dispatched strictly ONCE: directly to targetPid if known, or fallback to .cghidEventTap.
    public func inject(text: String, targetPid: pid_t? = nil) async {
        guard !text.isEmpty else { return }
        
        let myPid = ProcessInfo.processInfo.processIdentifier
        var effectivePid: pid_t? = (targetPid != nil && targetPid != myPid && targetPid! > 0) ? targetPid : nil
        
        // 1. Identify and activate the target application
        var targetApp: NSRunningApplication?
        if let pid = effectivePid {
            targetApp = NSRunningApplication(processIdentifier: pid)
        }
        if targetApp == nil {
            targetApp = NSWorkspace.shared.runningApplications.first(where: {
                $0.processIdentifier != myPid && $0.activationPolicy == .regular && $0.isActive
            }) ?? NSWorkspace.shared.frontmostApplication
            if let found = targetApp, found.processIdentifier != myPid {
                effectivePid = found.processIdentifier
            }
        }
        
        if let app = targetApp, app.processIdentifier != myPid {
            app.activate(options: [])
            NSApplication.shared.yieldActivation(to: app)
            // Settle time for WindowServer to establish active key responder & blinking cursor
            try? await Task.sleep(nanoseconds: 80_000_000) // 80ms
        }
        
        // 2. Put text onto pasteboard with transient markers
        let pb = NSPasteboard.general
        pb.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        pb.writeObjects([item])
        
        // 3. Dispatch authentic Cmd+V sequence strictly ONCE to prevent duplicate insertion
        let source = CGEventSource(stateID: .hidSystemState)
        let cmdCode: CGKeyCode = 0x37 // Left Command
        let vCode: CGKeyCode = 0x09   // ANSI 'V'
        
        // A. Cmd Down
        if let cmdDown = CGEvent(keyboardEventSource: source, virtualKey: cmdCode, keyDown: true) {
            cmdDown.flags = .maskCommand
            dispatchSingleEvent(cmdDown, targetPid: effectivePid)
        }
        usleep(10_000) // 10ms
        
        // B. V Down
        if let vDown = CGEvent(keyboardEventSource: source, virtualKey: vCode, keyDown: true) {
            vDown.flags = .maskCommand
            dispatchSingleEvent(vDown, targetPid: effectivePid)
        }
        usleep(25_000) // 25ms dwell time
        
        // C. V Up
        if let vUp = CGEvent(keyboardEventSource: source, virtualKey: vCode, keyDown: false) {
            vUp.flags = .maskCommand
            dispatchSingleEvent(vUp, targetPid: effectivePid)
        }
        usleep(10_000) // 10ms
        
        // D. Cmd Up
        if let cmdUp = CGEvent(keyboardEventSource: source, virtualKey: cmdCode, keyDown: false) {
            cmdUp.flags = []
            dispatchSingleEvent(cmdUp, targetPid: effectivePid)
        }
        
        print("[LeapWispr Injector] Successfully injected \(text.count) characters into PID \(effectivePid ?? 0)")
    }
    
    /// Dispatches event to target PID if available, otherwise falls back to system HID tap.
    /// Never dispatches to both, preventing duplicate paste.
    private func dispatchSingleEvent(_ event: CGEvent, targetPid: pid_t?) {
        if let pid = targetPid, pid > 0 {
            event.postToPid(pid)
        } else {
            event.post(tap: .cghidEventTap)
        }
    }
}
